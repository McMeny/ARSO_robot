"""Writes the tentacle-planner scenario worlds (run from this folder: python3 make_scenarios.py).
The walker spawns at (0, 0) facing +x in every one. Walls are 'wall_*' (structure); obstacles are
'aisle_*', so the hazard tracker tags them. Everything is 0.8-1 m tall, above the lidar."""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
STORE = os.path.join(HERE, '..', 'my_world.sdf')

WALL = (0.85, 0.85, 0.8)
OBSTACLE = (0.9, 0.35, 0.15)


def box(name, x, y, sx, sy, h=1.0, yaw=0.0, colour=WALL):
    c = ' '.join(f'{v:.2f}' for v in colour)
    return f'''    <model name="{name}">
      <static>true</static>
      <pose>{x:.3f} {y:.3f} {h / 2:.3f} 0 0 {yaw:.3f}</pose>
      <link name="link">
        <collision name="collision"><geometry><box><size>{sx:.3f} {sy:.3f} {h:.3f}</size></box></geometry></collision>
        <visual name="visual">
          <geometry><box><size>{sx:.3f} {sy:.3f} {h:.3f}</size></box></geometry>
          <material><ambient>{c} 1</ambient><diffuse>{c} 1</diffuse></material>
        </visual>
      </link>
    </model>
'''


def cylinder(name, x, y, r, h=0.8, colour=OBSTACLE):
    c = ' '.join(f'{v:.2f}' for v in colour)
    return f'''    <model name="{name}">
      <static>true</static>
      <pose>{x:.3f} {y:.3f} {h / 2:.3f} 0 0 0</pose>
      <link name="link">
        <collision name="collision"><geometry><cylinder><radius>{r:.3f}</radius><length>{h:.3f}</length></cylinder></geometry></collision>
        <visual name="visual">
          <geometry><cylinder><radius>{r:.3f}</radius><length>{h:.3f}</length></cylinder></geometry>
          <material><ambient>{c} 1</ambient><diffuse>{c} 1</diffuse></material>
        </visual>
      </link>
    </model>
'''


def room(x0, x1, y0, y1, t=0.15):
    """Four walls around x0..x1, y0..y1."""
    w, h = x1 - x0, y1 - y0
    return (box('wall_n', (x0 + x1) / 2, y1 + t / 2, w + 2 * t, t) + box('wall_s', (x0 + x1) / 2, y0 - t / 2, w + 2 * t, t)
            + box('wall_e', x1 + t / 2, (y0 + y1) / 2, t, h) + box('wall_w', x0 - t / 2, (y0 + y1) / 2, t, h))


SCENARIOS = {
    # 1 + 8: open space - straight WALK, STEER curves and pivots, grip release
    'open': ('Open space, 18 x 12 m', room(-4, 14, -6, 6)),
    # 2: a 1.5 m corridor, 9 m long - centred and steady
    'corridor': ('Corridor 1.5 m wide', room(-1.5, 9, -0.75, 0.75)),
    # 3: corridor ending in a T: branches left and right at x = 4..5.5
    'tjunction': ('Aisle end / T-junction', (
        box('wall_end', 6.075, 0, 0.15, 8.3)                       # far wall of the cross aisle
        + box('wall_left', 1.25, 0.825, 5.5, 0.15) + box('wall_right', 1.25, -0.825, 5.5, 0.15)
        + box('wall_back', -1.575, 0, 0.15, 1.8)
        + box('wall_left_far', 4.0, 2.325, 0.15, 3.0) + box('wall_right_far', 4.0, -2.325, 0.15, 3.0)
        + box('wall_cross_n', 5.0, 4.075, 2.3, 0.15) + box('wall_cross_s', 5.0, -4.075, 2.3, 0.15))),
    # 4 + 5: one obstacle slightly off-centre in a 3 m aisle, 1.35 m clear beside it (registered / unregistered
    #        via the EEG emulator). A 2.4 m aisle leaves 1.05 m, which the walker + user only fit through dead straight.
    'obstacle': ('Single obstacle ahead', room(-1.5, 9, -1.5, 1.5) + box('aisle_box', 3.5, 0.1, 0.5, 0.5, 0.8, colour=OBSTACLE)),
    # 6: clutter in a 3.5 m wide space, alternating sides about 3 m apart (a walker with a person behind it
    #    can't slalom tighter than that); every gap at least 1.2 m (the walker + user + margins need 0.84 m)
    'cluttered': ('Cluttered aisle', room(-1.5, 15, -1.75, 1.75)
                  + box('aisle_crate_1', 2.5, 0.85, 0.6, 0.6, 0.8, colour=OBSTACLE)
                  + cylinder('aisle_sign_1', 5.3, -0.75, 0.18)
                  + box('aisle_cart_1', 8.2, 0.9, 1.0, 0.6, 0.9, 0.3, colour=OBSTACLE)
                  + box('aisle_boxes_1', 11.0, -0.85, 0.7, 0.7, 0.8, 0.6, colour=OBSTACLE)
                  + cylinder('aisle_bucket_1', 13.4, 0.5, 0.2)),
    # 7: a 2.4 m wide dead end, 4 m deep - wide enough to turn round in
    'deadend': ('Dead end', box('wall_end', 4.075, 0, 0.15, 2.7) + box('wall_left', 1.25, 1.275, 5.8, 0.15)
                + box('wall_right', 1.25, -1.275, 5.8, 0.15)),
}


def main():
    store = open(STORE).read()
    head = store[:store.index('    <model name="wall_north">')]
    head = head[head.index('<sdf'):]
    for name, (title, models) in SCENARIOS.items():
        with open(os.path.join(HERE, f'{name}.sdf'), 'w') as f:
            f.write(f'<?xml version="1.0"?>\n<!-- Scenario "{name}": {title}. Generated by make_scenarios.py. -->\n')
            f.write(head + models + '\n  </world>\n</sdf>\n')
        print('wrote', name)


if __name__ == '__main__':
    main()
