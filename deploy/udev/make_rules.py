#!/usr/bin/env python3
"""Write udev rules for /dev/eyesteer_mcu and /dev/lidar from config/hardware.yaml (USB VID/PID).
Find your device's IDs with:  udevadm info -a -n /dev/ttyACM0 | grep -E 'idVendor|idProduct|serial'
If two devices share a VID/PID (e.g. two CP2102 adapters), add ATTRS{serial}=="..." to the rule."""
from pathlib import Path

import yaml

hw = yaml.safe_load((Path(__file__).resolve().parents[2] / "config/hardware.yaml").read_text())
m, l = hw["mcu"], hw["lidar"]
print("# GENERATED by deploy/udev/make_rules.py from config/hardware.yaml")
print(f'SUBSYSTEM=="tty", ATTRS{{idVendor}}=="{m["usb_vid"]}", ATTRS{{idProduct}}=="{m["usb_pid"]}", '
      f'SYMLINK+="{Path(m["device"]).name}", MODE="0666", GROUP="dialout"')
print(f'SUBSYSTEM=="tty", ATTRS{{idVendor}}=="{l["usb_vid"]}", ATTRS{{idProduct}}=="{l["usb_pid"]}", '
      f'SYMLINK+="{Path(l["device"]).name}", MODE="0666", GROUP="dialout"')
