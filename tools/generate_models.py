ROBOT_FILE = {"field_robot": "robot_field.yaml", "walker": "robot_walker.yaml"}

HEADER = "GENERATED by tools/generate_models.py from config/{src}. Do not edit; run `make generate`."


def load_yaml(p: Path) -> dict:
    return yaml.safe_load(p.read_text(encoding="utf-8"))


def load_robot(name: str) -> dict:
    return load_yaml(ROOT / "config" / ROBOT_FILE[name])


def load_hw() -> dict:
    return load_yaml(ROOT / "config/hardware.yaml")


# ---------------------------------------------------------------- geometry
def derived(r: dict) -> dict:
    """All numbers the URDF/MJCF/firmware need, computed once."""
    w = r["wheels"]
    b = r["base"]
    d: dict[str, float] = {}
    d["wheel_radius"] = w["radius"]
    d["wheel_width"] = w["width"]
    d["wheel_separation"] = w["separation"]
    d["wheel_x"] = w["x"]
    d["wheel_mass"] = w["mass"]
    d["base_mass"] = b["mass"]
    d["base_height"] = b["height"]
    # base_link sits on the axle (z = wheel radius above base_footprint)
    d["base_z_center"] = b["ground_clearance"] + b["height"] / 2 - w["radius"]
    if b["shape"] == "cylinder":
        d["base_radius"] = b["radius"]
        d["base_x_center"] = 0.0
    else:
        d["base_length"] = b["length"]
        d["base_width"] = b["width"]
        d["base_x_center"] = b["x_offset"]
    L = r["lidar"]
    d["lidar_x"], d["lidar_y"], d["lidar_yaw"] = L["x"], L["y"], L["yaw"]
    d["lidar_z"] = L["z_above_ground"] - w["radius"]
    d["lidar_radius"], d["lidar_height"] = L["radius"], L["height"]
    d["imu_x"], d["imu_y"], d["imu_z"] = r["imu"]["x"], r["imu"]["y"], r["imu"]["z_above_ground"] - w["radius"]
    c = r["camera"]
    d["camera_x"], d["camera_y"], d["camera_z"] = c["x"], c["y"], c["z_above_ground"] - w["radius"]
    if "handles" in r:
        h = r["handles"]
        d["handle_x"], d["handle_y"], d["handle_z"] = h["x"], h["y"], h["z_above_ground"] - w["radius"]
    return d


def footprint(r: dict) -> dict:
    fp = r["footprint"]
    if fp["type"] == "circle":
        return {"type": "circle", "radius": fp["radius"], "padding": fp["padding"]}
    b, uz, h = r["base"], r["user_zone"], r["handles"]
    front = b["x_offset"] + b["length"] / 2
    rear = h["x"] - uz["depth_behind_handles"]
    half_w = b["width"] / 2 + uz["side_margin"]
    poly = [[front, half_w], [rear, half_w], [rear, -half_w], [front, -half_w]]
    poly = [[round(x, 4), round(y, 4)] for x, y in poly]
    radius = max(math.hypot(x, y) for x, y in poly)
    return {"type": "polygon", "polygon": poly, "radius": round(radius, 4), "padding": fp["padding"],
            "inscribed_radius": round(min(front, -rear, half_w), 4)}


# ---------------------------------------------------------------- inertia
def inertia_box(m, x, y, z):
    return (m * (y * y + z * z) / 12, m * (x * x + z * z) / 12, m * (x * x + y * y) / 12)


def inertia_cyl(m, r, h):  # axis = local z
    a = m * (3 * r * r + h * h) / 12
    return (a, a, m * r * r / 2)


def inertia_sphere(m, r):
    a = 2 * m * r * r / 5
    return (a, a, a)


# ---------------------------------------------------------------- URDF builder
class U:
    """Formats a named property either as ${name} (xacro) or as its value (plain)."""

    def __init__(self, d: dict, xacro: bool):
        self.d, self.xacro = d, xacro

    def __call__(self, name: str, scale: float = 1.0, add: float = 0.0) -> str:
        if self.xacro:
            expr = name
            if scale != 1.0:
                expr = f"{scale}*{expr}"
            if add != 0.0:
                expr = f"{expr}+({add})"
            return "${" + expr + "}"
        return fmt(self.d[name] * scale + add)


def fmt(v: float) -> str:
    s = f"{v:.6f}".rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


def inertial_xml(m, ixyz, xyz="0 0 0") -> str:
    ixx, iyy, izz = ixyz
    return (f'    <inertial><origin xyz="{xyz}" rpy="0 0 0"/><mass value="{fmt(m)}"/>'
            f'<inertia ixx="{ixx:.6e}" ixy="0" ixz="0" iyy="{iyy:.6e}" iyz="0" izz="{izz:.6e}"/></inertial>\n')


def build_urdf(r: dict, hw: dict, xacro: bool, backend: str = "mujoco", device: str | None = None) -> str:
    d = derived(r)
    p = U(d, xacro)
    name = r["name"]
    out = ['<?xml version="1.0"?>', f"<!-- {HEADER.format(src=ROBOT_FILE[name])} -->"]
    if xacro:
        out.append(f'<robot name="{name}" xmlns:xacro="http://www.ros.org/wiki/xacro">')
        out.append('  <xacro:arg name="backend" default="mujoco"/>  <!-- mujoco | mujoco_hil | real -->')
        out.append(f'  <xacro:arg name="device" default="{hw["mcu"]["device"]}"/>')
        for k, v in d.items():
            out.append(f'  <xacro:property name="{k}" value="{fmt(v)}"/>')
    else:
        out.append(f'<robot name="{name}">')
    out.append('  <material name="body"><color rgba="0.85 0.85 0.88 1"/></material>')
    out.append('  <material name="dark"><color rgba="0.15 0.15 0.15 1"/></material>')
    out.append('  <material name="accent"><color rgba="0.1 0.45 0.9 1"/></material>')
    out.append('  <link name="base_footprint"/>')
    out.append('  <joint name="base_joint" type="fixed"><parent link="base_footprint"/><child link="base_link"/>'
               f'<origin xyz="0 0 {p("wheel_radius")}" rpy="0 0 0"/></joint>')

    # base_link
    b = r["base"]
    if b["shape"] == "cylinder":
        geom = f'<cylinder radius="{p("base_radius")}" length="{p("base_height")}"/>'
        ine = inertia_cyl(d["base_mass"], d["base_radius"], d["base_height"])
    else:
        geom = f'<box size="{p("base_length")} {p("base_width")} {p("base_height")}"/>'
        ine = inertia_box(d["base_mass"], d["base_length"], d["base_width"], d["base_height"])
    org = f'<origin xyz="{p("base_x_center")} 0 {p("base_z_center")}" rpy="0 0 0"/>'
    bl = ['  <link name="base_link">',
          f'    <visual>{org}<geometry>{geom}</geometry><material name="body"/></visual>',
          f'    <collision>{org}<geometry>{geom}</geometry></collision>']
    if "handles" in r:  # walker uprights + handle bar (visual + collision, primitives only)
        hz = d["handle_z"]
        for side, sy in (("left", 1), ("right", -1)):
            zc = (hz + d["base_z_center"]) / 2
            ln = hz - d["base_z_center"]
            bl.append(f'    <visual><origin xyz="{fmt(d["handle_x"])} {fmt(sy * d["handle_y"])} {fmt(zc)}" rpy="0 0 0"/>'
                      f'<geometry><cylinder radius="0.015" length="{fmt(ln)}"/></geometry><material name="dark"/></visual>')
        bx = r["battery_box"]
        bz = d["base_z_center"] - d["base_height"] / 2 - bx["height"] / 2
        bl.append(f'    <visual><origin xyz="{fmt(bx["x"])} 0 {fmt(bz)}" rpy="0 0 0"/><geometry><box size="{fmt(bx["length"])} '
                  f'{fmt(bx["width"])} {fmt(bx["height"])}"/></geometry><material name="dark"/></visual>')
    bl.append(inertial_xml(d["base_mass"], ine, f'{fmt(d["base_x_center"])} 0 {fmt(d["base_z_center"])}').rstrip())
    bl.append("  </link>")
    out += bl

    # wheels: continuous, axis +y on both -> positive velocity drives +x (tested)
    wi = inertia_cyl(d["wheel_mass"], d["wheel_radius"], d["wheel_width"])
    wi = (wi[0], wi[2], wi[1])  # cylinder axis along y in the link frame
    for side, sy in (("left", 1), ("right", -1)):
        out.append(f'  <link name="{side}_wheel_link">')
        g = f'<cylinder radius="{p("wheel_radius")}" length="{p("wheel_width")}"/>'
        out.append(f'    <visual><origin xyz="0 0 0" rpy="-1.570796 0 0"/><geometry>{g}</geometry><material name="dark"/></visual>')
        out.append(f'    <collision><origin xyz="0 0 0" rpy="-1.570796 0 0"/><geometry>{g}</geometry></collision>')
        out.append(inertial_xml(d["wheel_mass"], wi).rstrip())
        out.append("  </link>")
        out.append(f'  <joint name="{side}_wheel_joint" type="continuous"><parent link="base_link"/><child link="{side}_wheel_link"/>'
                   f'<origin xyz="{p("wheel_x")} {p("wheel_separation", 0.5 * sy)} 0" rpy="0 0 0"/><axis xyz="0 1 0"/></joint>')

    for c in r["casters"]:
        z = c["radius"] - d["wheel_radius"]
        out.append(f'  <link name="{c["name"]}_link">')
        out.append(f'    <visual><geometry><sphere radius="{fmt(c["radius"])}"/></geometry><material name="dark"/></visual>')
        out.append(f'    <collision><geometry><sphere radius="{fmt(c["radius"])}"/></geometry></collision>')
        out.append(inertial_xml(0.05, inertia_sphere(0.05, c["radius"])).rstrip())
        out.append("  </link>")
        out.append(f'  <joint name="{c["name"]}_joint" type="fixed"><parent link="base_link"/><child link="{c["name"]}_link"/>'
                   f'<origin xyz="{fmt(c["x"])} {fmt(c["y"])} {fmt(z)}" rpy="0 0 0"/></joint>')

    # sensors
    lg = f'<cylinder radius="{p("lidar_radius")}" length="{p("lidar_height")}"/>'
    out.append('  <link name="laser_frame">')
    out.append(f'    <visual><geometry>{lg}</geometry><material name="accent"/></visual>')
    out.append(f'    <collision><geometry>{lg}</geometry></collision>')
    out.append(inertial_xml(0.17, inertia_cyl(0.17, d["lidar_radius"], d["lidar_height"])).rstrip())
    out.append("  </link>")
    out.append('  <joint name="laser_joint" type="fixed"><parent link="base_link"/><child link="laser_frame"/>'
               f'<origin xyz="{p("lidar_x")} {p("lidar_y")} {p("lidar_z")}" rpy="0 0 {p("lidar_yaw")}"/></joint>')
    out.append('  <link name="imu_link"/>')
    out.append('  <joint name="imu_joint" type="fixed"><parent link="base_link"/><child link="imu_link"/>'
               f'<origin xyz="{p("imu_x")} {p("imu_y")} {p("imu_z")}" rpy="0 0 0"/></joint>')
    out.append('  <link name="camera_link"/>')
    out.append('  <joint name="camera_joint" type="fixed"><parent link="base_link"/><child link="camera_link"/>'
               f'<origin xyz="{p("camera_x")} {p("camera_y")} {p("camera_z")}" rpy="0 0 0"/></joint>')
    out.append('  <link name="camera_optical_frame"/>')
    out.append('  <joint name="camera_optical_joint" type="fixed"><parent link="camera_link"/><child link="camera_optical_frame"/>'
               '<origin xyz="0 0 0" rpy="-1.570796 0 -1.570796"/></joint>')
    if "handles" in r:
        for side, sy in (("left", 1), ("right", -1)):
            out.append(f'  <link name="handle_{side}_ft"/>')
            out.append(f'  <joint name="handle_{side}_ft_joint" type="fixed"><parent link="base_link"/><child link="handle_{side}_ft"/>'
                       f'<origin xyz="{p("handle_x")} {p("handle_y", sy)} {p("handle_z")}" rpy="0 0 0"/></joint>')
            out.append(f'  <link name="grip_{side}"/>')
            out.append(f'  <joint name="grip_{side}_joint" type="fixed"><parent link="handle_{side}_ft"/><child link="grip_{side}"/>'
                       '<origin xyz="-0.03 0 0.02" rpy="0 0 0"/></joint>')

    # ros2_control
    rc = ros2_control_xml(r, hw, xacro, backend, device)
    if rc:
        out.append(rc)
    out.append("</robot>")
    return "\n".join(out) + "\n"


def ros2_control_xml(r: dict, hw: dict, xacro: bool, backend: str, device: str | None) -> str:
    lim = r["limits"]
    wmax = lim["v_max"] / r["wheels"]["radius"] * 1.2
    mcu = hw["mcu"]
    pid = r["pid"]
    body = [f'  <ros2_control name="{r["name"]}_system" type="system">',
            "    <hardware>",
            "      <plugin>diffdrive_arduino/DiffDriveArduinoHardware</plugin>",
            '      <param name="left_wheel_name">left_wheel_joint</param>',
            '      <param name="right_wheel_name">right_wheel_joint</param>',
            f'      <param name="loop_rate">{mcu["pid_rate_hz"]}</param>',
            '      <param name="device">' + ("$(arg device)" if xacro else (device or mcu["device"])) + "</param>",
            f'      <param name="baud_rate">{mcu["baud"]}</param>',
            f'      <param name="timeout_ms">{mcu["serial_timeout_ms"]}</param>',
            f'      <param name="enc_counts_per_rev">{hw["encoders"]["counts_per_rev"]}</param>',
            f'      <param name="pid_p">{pid["kp"]}</param>',
            f'      <param name="pid_d">{pid["kd"]}</param>',
            f'      <param name="pid_i">{pid["ki"]}</param>',
            f'      <param name="pid_o">{pid["ko"]}</param>',
            "    </hardware>"]
    for side in ("left", "right"):
        body += [f'    <joint name="{side}_wheel_joint">',
                 f'      <command_interface name="velocity"><param name="min">{fmt(-wmax)}</param><param name="max">{fmt(wmax)}</param></command_interface>',
                 '      <state_interface name="position"/>', '      <state_interface name="velocity"/>', "    </joint>"]
    body.append("  </ros2_control>")
    block = "\n".join(body)
    if xacro:
        return ("  <xacro:if value=\"${'$(arg backend)' in ['real', 'mujoco_hil']}\">\n" + block + "\n  </xacro:if>")
    return block if backend in ("real", "mujoco_hil") else ""


# ---------------------------------------------------------------- MJCF
def build_mjcf_robot(r: dict) -> str:
    """Robot as an MJCF <body> fragment (inserted into scenes by generate_world.py).

    Geom group 1 = robot (excluded from LiDAR rays), group 4 = attached walker user.
    """
    d = derived(r)
    wr = d["wheel_radius"]
    lines = [f'<!-- {HEADER.format(src=ROBOT_FILE[r["name"]])} -->',
             f'<body name="base_footprint" pos="0 0 0.002">',
             '  <freejoint name="root"/>',
             f'  <body name="base_link" pos="0 0 {fmt(wr)}">',
             f'    <site name="base_link_site" pos="0 0 0" size="0.01" group="5"/>']
    b = r["base"]
    bm = d["base_mass"]
    if b["shape"] == "cylinder":
        lines.append(f'    <geom name="chassis" type="cylinder" size="{fmt(d["base_radius"])} {fmt(d["base_height"] / 2)}" '
                     f'pos="0 0 {fmt(d["base_z_center"])}" mass="{fmt(bm)}" rgba="0.85 0.85 0.88 1" group="1"/>')
    else:
        lines.append(f'    <geom name="chassis" type="box" size="{fmt(d["base_length"] / 2)} {fmt(d["base_width"] / 2)} {fmt(d["base_height"] / 2)}" '
                     f'pos="{fmt(d["base_x_center"])} 0 {fmt(d["base_z_center"])}" mass="{fmt(bm)}" rgba="0.85 0.85 0.88 1" group="1"/>')
        bx = r["battery_box"]
        bz = d["base_z_center"] - d["base_height"] / 2 - bx["height"] / 2
        lines.append(f'    <geom name="battery" type="box" size="{fmt(bx["length"] / 2)} {fmt(bx["width"] / 2)} {fmt(bx["height"] / 2)}" '
                     f'pos="{fmt(bx["x"])} 0 {fmt(bz)}" mass="0.01" rgba="0.2 0.2 0.2 1" group="1" contype="0" conaffinity="0"/>')
        hz = d["handle_z"]
        for side, sy in (("left", 1), ("right", -1)):
            lines.append(f'    <geom name="upright_{side}" type="capsule" fromto="{fmt(d["handle_x"])} {fmt(sy * d["handle_y"])} {fmt(d["base_z_center"])} '
                         f'{fmt(d["handle_x"])} {fmt(sy * d["handle_y"])} {fmt(hz)}" size="0.015" mass="0.01" rgba="0.2 0.2 0.2 1" group="1" contype="0" conaffinity="0"/>')
            lines.append(f'    <site name="handle_{side}_ft" pos="{fmt(d["handle_x"])} {fmt(sy * d["handle_y"])} {fmt(hz)}" size="0.02" rgba="1 0.5 0 1" group="1"/>')
        lines.append(f'    <geom name="handlebar" type="capsule" fromto="{fmt(d["handle_x"])} {fmt(d["handle_y"])} {fmt(hz)} {fmt(d["handle_x"])} {fmt(-d["handle_y"])} {fmt(hz)}" '
                     f'size="0.012" mass="0.01" rgba="0.2 0.2 0.2 1" group="1" contype="0" conaffinity="0"/>')
    for c in r["casters"]:
        z = c["radius"] - wr
        lines.append(f'    <geom name="{c["name"]}" type="sphere" size="{fmt(c["radius"])}" pos="{fmt(c["x"])} {fmt(c["y"])} {fmt(z)}" '
                     f'mass="0.05" priority="1" friction="0.0005 0.0001 0.0001" condim="1" rgba="0.15 0.15 0.15 1" group="1"/>')
    lines.append(f'    <geom name="lidar" type="cylinder" size="{fmt(d["lidar_radius"])} {fmt(d["lidar_height"] / 2)}" '
                 f'pos="{fmt(d["lidar_x"])} {fmt(d["lidar_y"])} {fmt(d["lidar_z"])}" mass="0.17" rgba="0.1 0.45 0.9 1" group="1" contype="0" conaffinity="0"/>')
    lines.append(f'    <site name="laser_frame" pos="{fmt(d["lidar_x"])} {fmt(d["lidar_y"])} {fmt(d["lidar_z"])}" '
                 f'euler="0 0 {fmt(d["lidar_yaw"])}" size="0.01" group="5"/>')
    lines.append(f'    <site name="imu_link" pos="{fmt(d["imu_x"])} {fmt(d["imu_y"])} {fmt(d["imu_z"])}" size="0.01" group="5"/>')
    lines.append(f'    <site name="camera_link" pos="{fmt(d["camera_x"])} {fmt(d["camera_y"])} {fmt(d["camera_z"])}" size="0.01" group="5"/>')
    if "handles" in r:
        # simulated user behind the handles (visual only, group 4, excluded from LiDAR and contacts)
        ux = d["handle_x"] - 0.30
        lines.append(f'    <body name="walker_user" pos="{fmt(ux)} 0 {fmt(-wr)}">')
        lines.append('      <geom name="user_legs" type="capsule" fromto="0 0 0.1 0 0 0.85" size="0.13" mass="0.001" rgba="0.3 0.55 0.35 1" group="4" contype="0" conaffinity="0"/>')
        lines.append('      <geom name="user_torso" type="capsule" fromto="0 0 0.9 0 0 1.4" size="0.17" mass="0.001" rgba="0.3 0.55 0.35 1" group="4" contype="0" conaffinity="0"/>')
        lines.append('      <geom name="user_head" type="sphere" pos="0 0 1.6" size="0.11" mass="0.001" rgba="0.9 0.75 0.6 1" group="4" contype="0" conaffinity="0"/>')
        lines.append('      <site name="user_eyes" pos="0.08 0 1.62" size="0.01" group="5"/>')
        lines.append("    </body>")
    for side, sy in (("left", 1), ("right", -1)):
        lines.append(f'    <body name="{side}_wheel_link" pos="{fmt(d["wheel_x"])} {fmt(sy * d["wheel_separation"] / 2)} 0">')
        lines.append(f'      <joint name="{side}_wheel_joint" type="hinge" axis="0 1 0" damping="0.01"/>')
        lines.append(f'      <geom name="{side}_wheel" type="cylinder" size="{fmt(wr)} {fmt(d["wheel_width"] / 2)}" quat="0.707107 0.707107 0 0" '
                     f'mass="{fmt(d["wheel_mass"])}" friction="1.2 0.01 0.001" condim="3" rgba="0.12 0.12 0.12 1" group="1"/>')
        lines.append("    </body>")
    lines.append("  </body>")
    lines.append("</body>")
    return "\n".join(lines) + "\n"


def build_mjcf_actuators(r: dict) -> str:
    wr = r["wheels"]["radius"]
    wmax = r["limits"]["v_max"] / wr * 1.5
    kv = 2.0 if r["name"] == "field_robot" else 30.0
    frc = 3.0 if r["name"] == "field_robot" else 60.0
    out = [f'<!-- {HEADER.format(src=ROBOT_FILE[r["name"]])} -->', "<actuator>"]
    for side in ("left", "right"):
        out.append(f'  <velocity name="{side}_wheel_motor" joint="{side}_wheel_joint" kv="{kv}" ctrlrange="{fmt(-wmax)} {fmt(wmax)}" '
                   f'forcerange="{-frc} {frc}"/>')
    out += ["</actuator>", "<sensor>"]
    for side in ("left", "right"):
        out.append(f'  <jointpos name="{side}_encoder" joint="{side}_wheel_joint"/>')
        out.append(f'  <jointvel name="{side}_wheel_vel" joint="{side}_wheel_joint"/>')
    out += ['  <gyro name="imu_gyro" site="imu_link"/>', '  <accelerometer name="imu_accel" site="imu_link"/>',
            '  <framequat name="imu_quat" objtype="site" objname="imu_link"/>', "</sensor>"]
    return "\n".join(out) + "\n"


def build_mjcf_standalone(r: dict) -> str:
    """Self-contained MJCF (flat floor + robot), used for the URDF<->MJCF consistency test."""
    body = build_mjcf_robot(r)
    acts = build_mjcf_actuators(r)
    return (f'<mujoco model="{r["name"]}">\n  <option timestep="0.002" integrator="implicitfast"/>\n'
            '  <worldbody>\n    <geom name="floor" type="plane" size="20 20 0.1" rgba="0.6 0.6 0.6 1"/>\n'
            + indent(body, 4) + "  </worldbody>\n" + indent(acts.split("\n", 1)[1], 2) + "</mujoco>\n")


def indent(s: str, n: int) -> str:
    pad = " " * n
    return "".join(pad + line + "\n" if line.strip() else "\n" for line in s.splitlines())


# ---------------------------------------------------------------- controller YAML, nav2, firmware
def controllers_yaml(r: dict, hw: dict) -> str:
    lim = r["limits"]
    w = r["wheels"]
    cfg = {
        "controller_manager": {"ros__parameters": {
            # 50 Hz command/read loop; diffdrive_arduino's loop_rate (= firmware PID rate, 30 Hz) only sets the
            # units of 'm' (counts per PID loop), so the two rates are independent. 50 Hz cuts command latency.
            "update_rate": 50,
            "diff_cont": {"type": "diff_drive_controller/DiffDriveController"},
            "joint_broad": {"type": "joint_state_broadcaster/JointStateBroadcaster"}}},
        "diff_cont": {"ros__parameters": {
            "publish_rate": 50.0, "base_frame_id": "base_footprint", "odom_frame_id": "odom",
            "left_wheel_names": ["left_wheel_joint"], "right_wheel_names": ["right_wheel_joint"],
            "wheel_separation": w["separation"], "wheel_radius": w["radius"],
            "use_stamped_vel": False, "enable_odom_tf": True, "cmd_vel_timeout": 0.5,
            "pose_covariance_diagonal": [0.001, 0.001, 0.001, 0.001, 0.001, 0.01],
            "twist_covariance_diagonal": [0.001, 0.001, 0.001, 0.001, 0.001, 0.01],
            "linear.x.has_velocity_limits": True, "linear.x.has_acceleration_limits": True,
            "linear.x.max_velocity": lim["v_max"], "linear.x.min_velocity": -lim["v_max"],
            "linear.x.max_acceleration": lim["a_max"], "linear.x.min_acceleration": -lim["a_max"],
            "angular.z.has_velocity_limits": True, "angular.z.has_acceleration_limits": True,
            "angular.z.max_velocity": lim["w_max"], "angular.z.min_velocity": -lim["w_max"],
            "angular.z.max_acceleration": lim["alpha_max"], "angular.z.min_acceleration": -lim["alpha_max"]}},
    }
    return f"# {HEADER.format(src=ROBOT_FILE[r['name']])}\n" + yaml.safe_dump(cfg, sort_keys=False)


def firmware_header(r: dict, hw: dict) -> str:
    w = r["wheels"]
    lim = r["limits"]
    mcu = hw["mcu"]
    cpr = hw["encoders"]["counts_per_rev"]
    counts_per_m = cpr / (2 * math.pi * w["radius"])
    max_counts_per_loop = lim["v_max"] * 1.2 * counts_per_m / mcu["pid_rate_hz"]
    tag = r["name"].upper()
    md = hw["motor_driver"]
    L = [f"// {HEADER.format(src=ROBOT_FILE[r['name']] + ' + hardware.yaml')}",
         f"#pragma once", f"#define ROBOT_NAME \"{r['name']}\"",
         f"#define WHEEL_RADIUS_M {w['radius']}f", f"#define WHEEL_SEPARATION_M {w['separation']}f",
         f"#define ENCODER_CPR {cpr}", f"#define PID_RATE_HZ {mcu['pid_rate_hz']}",
         f"#define BAUD_RATE {mcu['baud']}", f"#define WATCHDOG_MS {mcu['watchdog_ms']}",
         f"#define MAX_PWM {mcu['max_pwm']}",
         f"#define FF_COUNTS_AT_MAX_PWM {hw['encoders'].get('ff_counts_per_loop_at_max_pwm') or max(1, round(max_counts_per_loop * 1.25))}",
         f"#define MAX_COUNTS_PER_LOOP {max(1, round(max_counts_per_loop))}",
         f"#define MAX_ACCEL_COUNTS_PER_LOOP2 {max(1, round(lim['a_max'] * counts_per_m / mcu['pid_rate_hz'] ** 2 * 4))}",
         f"#define PID_KP {r['pid']['kp']}", f"#define PID_KD {r['pid']['kd']}",
         f"#define PID_KI {r['pid']['ki']}", f"#define PID_KO {r['pid']['ko']}",
         f"#define INVERT_LEFT_MOTOR {int(md['invert_left'])}", f"#define INVERT_RIGHT_MOTOR {int(md['invert_right'])}",
         f"#define INVERT_LEFT_ENCODER {int(md['invert_left_encoder'])}", f"#define INVERT_RIGHT_ENCODER {int(md['invert_right_encoder'])}",
         f"#define MOTOR_DRIVER_L298N {int(md['type'] == 'l298n')}",
         f"#define IS_WALKER {int(r['name'] == 'walker')}"]
    if r["name"] == "walker":
        L += [f"#define LOAD_CELL_SCALE_LEFT {hw['walker']['load_cell_scale'][0]}f",
              f"#define LOAD_CELL_SCALE_RIGHT {hw['walker']['load_cell_scale'][1]}f",
              f"#define GRIP_ACTIVE_LOW {int(hw['walker']['grip_active_low'])}"]
    L.append("")
    for board, pins in md["pins"].items():
        L.append(f"#if defined(EYESTEER_BOARD_{board.upper()})")
        for k, v in pins.items():
            L.append(f"#define PIN_{k.upper()} {v}")
        L.append("#endif")
    return "\n".join(L) + "\n"


def nav2_footprint_yaml(r: dict) -> dict:
    fp = footprint(r)
    out = {"robot": r["name"], **fp, "inflation_radius": r["nav"]["inflation_radius"],
           "cost_scaling_factor": r["nav"]["cost_scaling_factor"]}
    if fp["type"] == "polygon":
        out["footprint_string"] = json.dumps(fp["polygon"]).replace(" ", "")
    return out


def collision_polygons(r: dict, grow: float) -> list[list[float]]:
    sys.path.insert(0, str(ROOT))
    from eyesteer_core.control.footprint import monitor_polygon
    return monitor_polygon(footprint(r), grow)


def render_template(text: str, r: dict, extra: dict) -> str:
    fp = footprint(r)
    if fp["type"] == "circle":
        fp_line = f"robot_radius: {fp['radius'] + fp['padding']}"
    else:
        fp_line = f"footprint: \"{json.dumps(fp['polygon']).replace(' ', '')}\""
    subs = {"FOOTPRINT_LINE": fp_line, "INFLATION_RADIUS": str(r["nav"]["inflation_radius"]),
            "COST_SCALING": str(r["nav"]["cost_scaling_factor"]),
            "V_MAX": str(r["limits"]["v_max"]), "W_MAX": str(r["limits"]["w_max"]),
            "A_MAX": str(r["limits"]["a_max"]), "ALPHA_MAX": str(r["limits"]["alpha_max"]),
            "XY_TOL": str(r["nav"]["goal_xy_tolerance"]),
            "YAW_TOL": fmt(math.radians(r["nav"]["goal_yaw_tolerance_deg"])),
            "SLOW_POLY": json.dumps(collision_polygons(r, 0.4)).replace(" ", ""),
            "STOP_POLY": json.dumps(collision_polygons(r, 0.1)).replace(" ", ""),
            "SLOW_POLY_FLAT": json.dumps([v for pt in collision_polygons(r, 0.4) for v in pt]),
            "STOP_POLY_FLAT": json.dumps([v for pt in collision_polygons(r, 0.1) for v in pt]),
            "ROBOT_NAME": r["name"]}
    subs.update(extra)
    for k, v in subs.items():
        text = text.replace("{{" + k + "}}", v)
    return text


def nav_variant(r: dict, variant: str) -> dict:
    """sim vs real Nav2 parameters: the real robot gets lower speed and more inflation (Section 18)."""
    walker = r["name"] == "walker"
    v = (0.4 if walker else 0.45) if variant == "sim" else (0.3 if walker else 0.3)
    infl = r["nav"]["inflation_radius"] + (0.1 if variant == "real" else 0.0)
    return {"VARIANT": variant, "NAV_V": str(v), "LOOKAHEAD": str(r["nav"].get("lookahead", 0.6)),
            "ROT_V": str(0.5 if walker else 0.8), "PROGRESS_TIMEOUT": "45.0" if walker else "20.0", "INFLATION_RADIUS": f"{infl:.2f}"}


def write(path: Path, text: str):
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists() and path.read_text(encoding="utf-8") == text:
        return
    path.write_text(text, newline="\n")


def main() -> int:
    hw = load_hw()
    for name in ROBOTS:
        r = load_robot(name)
        write(DESC / "urdf" / f"{name}.urdf.xacro", build_urdf(r, hw, xacro=True))
        write(DESC / "urdf" / f"{name}.urdf", build_urdf(r, hw, xacro=False, backend="mujoco"))
        write(DESC / "urdf" / f"{name}_real.urdf", build_urdf(r, hw, xacro=False, backend="real"))
        write(DESC / "urdf" / f"{name}_hil.urdf", build_urdf(r, hw, xacro=False, backend="mujoco_hil", device="/tmp/eyesteer_mcu"))
        write(GEN / "mjcf" / f"{name}_body.xml", build_mjcf_robot(r))
        write(GEN / "mjcf" / f"{name}_actuators.xml", build_mjcf_actuators(r))
        write(GEN / "mjcf" / f"{name}.xml", build_mjcf_standalone(r))
        write(BRINGUP / "config" / "generated" / f"{name}_controllers.yaml", controllers_yaml(r, hw))
        write(GEN / f"{name}_footprint.yaml", f"# {HEADER.format(src=ROBOT_FILE[name])}\n" + yaml.safe_dump(nav2_footprint_yaml(r), sort_keys=False))
        write(GEN / f"{name}_geometry.json", json.dumps({"derived": derived(r), "footprint": footprint(r), "robot": r}, indent=2))
        write(FW_INC / f"robot_constants_{name}.h", firmware_header(r, hw))
        for tmpl in sorted((BRINGUP / "params" / "templates").glob("*.yaml")) if (BRINGUP / "params" / "templates").exists() else []:
            for variant in ("sim", "real"):
                write(BRINGUP / "params" / "generated" / f"{name}_{tmpl.stem}_{variant}.yaml",
                      render_template(tmpl.read_text(encoding="utf-8"), r, nav_variant(r, variant)))
        print(f"[generate] {name}: urdf/xacro, mjcf, controllers, footprint, firmware header")
    sys.path.insert(0, str(ROOT))
    from eyesteer_core.control.mux_rules import twist_mux_yaml
    write(BRINGUP / "params" / "generated" / "twist_mux.yaml",
          "# GENERATED from eyesteer_core/control/mux_rules.py (D8 priorities). Do not edit.\n"
          + yaml.safe_dump(twist_mux_yaml(), sort_keys=False))
    write(FW_INC / "robot_constants.h",
          f"// {HEADER.format(src='robot_*.yaml')}\n#pragma once\n#if defined(EYESTEER_WALKER)\n#include \"robot_constants_walker.h\"\n"
          "#else\n#include \"robot_constants_field_robot.h\"\n#endif\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
