"""Robot YAML -> xacro, expanded URDFs, MJCF, controller YAML, Nav2 footprint, firmware header (D14).

One builder emits the URDF; in xacro mode every dimension is written as ${property},
in plain mode the value is substituted, so the two can never disagree.
"""
