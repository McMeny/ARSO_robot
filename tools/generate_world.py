#!/usr/bin/env python3
"""World YAML (+ robot) -> MJCF scene, plus a prebuilt occupancy map for ROS localization.

Geom groups: 0 = static world, 1 = robot, 2 = moving people (seen by LiDAR),
3 = MR-overlay markers (virtual: never collide, never seen by LiDAR), 4 = attached walker user.
"""
from __future__ import annotations

import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "tools"))

from eyesteer_core.world import load_markers, load_world, rasterize, wall_boxes, write_ros_map  # noqa: E402
from generate_models import ROBOTS, build_mjcf_actuators, build_mjcf_robot, fmt, indent, load_robot, write  # noqa: E402

GEN = ROOT / "config/generated/mjcf"
MAPS = ROOT / "ros2_ws/src/eyesteer_bringup/maps"
WORLDS = ["field", "supermarket"]


def quat_z(yaw: float) -> str:
    return f"{math.cos(yaw / 2):.6f} 0 0 {math.sin(yaw / 2):.6f}"


def geom_xml(o: dict, default_rgba=(0.55, 0.45, 0.35, 1)) -> str:
    rgba = " ".join(fmt(v) for v in o.get("rgba", default_rgba))
    if o["type"] == "cylinder":
        return (f'<geom name="{o["name"]}" type="cylinder" size="{fmt(o["r"])} {fmt(o["h"] / 2)}" '
                f'pos="{fmt(o["x"])} {fmt(o["y"])} {fmt(o["h"] / 2)}" rgba="{rgba}" group="0"/>')
    return (f'<geom name="{o["name"]}" type="box" size="{fmt(o["sx"] / 2)} {fmt(o["sy"] / 2)} {fmt(o["h"] / 2)}" '
            f'pos="{fmt(o["x"])} {fmt(o["y"])} {fmt(o["h"] / 2)}" quat="{quat_z(o.get("yaw", 0.0))}" rgba="{rgba}" group="0"/>')


def build_scene(world_name: str, robot_name: str, marker_set: str | None = None) -> str:
    w = load_world(world_name)
    r = load_robot(robot_name)
    markers = load_markers(marker_set or w.default_markers)
    x0, y0, x1, y1 = w.bounds
    cx, cy = (x0 + x1) / 2, (y0 + y1) / 2
    span = max(x1 - x0, y1 - y0)
    sx, sy, syaw = w.start_pose
    L = [f'<mujoco model="{world_name}_{robot_name}">',
         "  <!-- GENERATED by tools/generate_world.py. Do not edit. -->",
         '  <compiler angle="radian"/>',
         '  <option timestep="0.002" integrator="implicitfast"/>',
         '  <visual><global offwidth="1920" offheight="1080"/><quality shadowsize="2048"/>'
         '<headlight ambient="0.35 0.35 0.35" diffuse="0.5 0.5 0.5"/></visual>',
         "  <asset>",
         '    <texture name="grid" type="2d" builtin="checker" rgb1="0.82 0.82 0.8" rgb2="0.74 0.74 0.72" width="512" height="512"/>',
         '    <material name="floor" texture="grid" texrepeat="20 20" reflectance="0.05"/>',
         '    <texture name="sky" type="skybox" builtin="gradient" rgb1="0.75 0.85 0.95" rgb2="0.95 0.95 0.97" width="256" height="256"/>',
         "  </asset>",
         "  <worldbody>",
         f'    <light name="sun" pos="{fmt(cx)} {fmt(cy)} 12" dir="0.3 0.2 -1" directional="true" diffuse="0.45 0.45 0.45" castshadow="true"/>',
         f'    <geom name="floor" type="plane" size="{fmt(span)} {fmt(span)} 0.1" pos="{fmt(cx)} {fmt(cy)} 0" material="floor" group="0"/>',
         f'    <camera name="top" pos="{fmt(cx)} {fmt(cy)} {fmt(span * 1.05)}" xyaxes="1 0 0 0 1 0" fovy="55"/>']
    if robot_name != "walker":
        # human observer standing at the field corner (the user's point of view for the field robot)
        L.append(f'    <camera name="user_pov" pos="{fmt(x0 - 0.3)} {fmt(y0 - 0.3)} 1.65" xyaxes="0.707 -0.707 0 0.25 0.25 0.935" fovy="70"/>')
    for o in wall_boxes(w):
        L.append("    " + geom_xml(o, (0.6, 0.6, 0.62, 0.35)))
    for o in w.obstacles:
        L.append("    " + geom_xml(o))
    for p in w.people:
        px, py = p["path"][0]
        L.append(f'    <body name="{p["name"]}" mocap="true" pos="{fmt(px)} {fmt(py)} 0">')
        L.append(f'      <geom name="{p["name"]}_body" type="capsule" fromto="0 0 0.25 0 0 1.45" size="{fmt(p["radius"])}" rgba="0.85 0.5 0.2 1" group="2"/>')
        L.append(f'      <geom name="{p["name"]}_head" type="sphere" pos="0 0 1.65" size="0.11" rgba="0.9 0.75 0.6 1" group="2" contype="0" conaffinity="0"/>')
        L.append("    </body>")
    for m in markers:
        # virtual MR-overlay marker: mocap so the overlay can billboard/pulse; never collides, never ray-cast
        L.append(f'    <body name="marker_{m.id}" mocap="true" pos="{fmt(m.x)} {fmt(m.y)} {fmt(m.z)}" quat="{quat_z(m.facing)}">')
        L.append(f'      <geom name="marker_{m.id}_panel" type="box" size="0.01 0.15 0.15" rgba="1 1 1 0.55" group="3" contype="0" conaffinity="0"/>')
        L.append(f'      <geom name="marker_{m.id}_ring" type="box" size="0.005 0.18 0.18" pos="-0.006 0 0" rgba="0.2 0.6 1 0.0" group="3" contype="0" conaffinity="0"/>')
        L.append("    </body>")
    body = build_mjcf_robot(r)
    body = body.replace('<body name="base_footprint" pos="0 0 0.002">',
                        f'<body name="base_footprint" pos="{fmt(sx)} {fmt(sy)} 0.002" quat="{quat_z(syaw)}">', 1)
    # chase camera: tracks the robot (mode=trackcom) with a fixed world-frame offset from the south-west,
    # so it never ends up behind a wall. MuJoCo interprets pos/xyaxes in the body frame at load, so
    # rotate the desired world offset by -start_yaw.
    dist = 4.2 if robot_name == "walker" else 6.0
    off_w = (-0.25 * dist, -0.55 * dist, 1.0 * dist)
    c, s_ = math.cos(-syaw), math.sin(-syaw)
    rot = lambda v: (c * v[0] - s_ * v[1], s_ * v[0] + c * v[1], v[2])
    fwd = [-off_w[0], -off_w[1], -off_w[2]]
    n = math.sqrt(sum(f * f for f in fwd))
    fwd = [f / n for f in fwd]
    xa = [fwd[1], -fwd[0], 0.0]
    xn = math.hypot(xa[0], xa[1])
    xa = [xa[0] / xn, xa[1] / xn, 0.0]
    ya = [xa[1] * fwd[2] - xa[2] * fwd[1], xa[2] * fwd[0] - xa[0] * fwd[2], xa[0] * fwd[1] - xa[1] * fwd[0]]
    ya = [-v for v in ya] if ya[2] < 0 else ya
    po, xr, yr = rot(off_w), rot(xa), rot(ya)
    cam = (f'<camera name="chase" mode="trackcom" pos="{fmt(po[0])} {fmt(po[1])} {fmt(po[2])}" '
           f'xyaxes="{" ".join(fmt(v) for v in xr)} {" ".join(fmt(v) for v in yr)}" fovy="55"/>')
    body = body.replace('<freejoint name="root"/>', '<freejoint name="root"/>\n  ' + cam, 1)
    if robot_name == "walker":
        body = body.replace('<site name="user_eyes" pos="0.08 0 1.62" size="0.01" group="5"/>',
                            '<site name="user_eyes" pos="0.08 0 1.62" size="0.01" group="5"/>\n'
                            '      <camera name="user_pov" pos="0.12 0 1.62" xyaxes="0 -1 0 0.17 0 0.985" fovy="75"/>', 1)
    L.append(indent(body, 4).rstrip("\n"))
    L.append("  </worldbody>")
    L.append(indent(build_mjcf_actuators(r).split("\n", 1)[1], 2).rstrip("\n"))
    L.append("</mujoco>")
    return "\n".join(L) + "\n"


def main() -> int:
    for wn in WORLDS:
        for rn in ROBOTS:
            write(GEN / f"scene_{wn}_{rn}.xml", build_scene(wn, rn))
        grid = rasterize(load_world(wn), 0.05)
        write_ros_map(grid, MAPS / wn, wn)
        print(f"[generate] world {wn}: scenes for {', '.join(ROBOTS)}, map {MAPS / wn}.pgm")
    return 0


if __name__ == "__main__":
    sys.exit(main())
