#!/usr/bin/env python3
"""Refresh rate -> frame-locked SSVEP frequency set (design decision D6).

Rules (all from config/bci.yaml `frequency_rules`):
  * f = R / n for integer n (exactly frame-locked), f_min <= f <= f_max
  * no member inside the alpha band (9.5-10.5 Hz) -> avoids false detections from alpha
  * no member within +-tol of a 2nd/3rd harmonic of another member
  * members at least `min_spacing` apart
Among valid sets, prefer (1) the most members inside the preferred band (strongest SSVEP),
(2) the largest minimum spacing, (3) the lowest mean frequency. The highest member is CANCEL.

If fewer than n_slots valid frequencies exist (e.g. 72 Hz), the largest valid set is
returned and `reduced: true` is set; the system then has fewer destination slots.
"""
from __future__ import annotations

import argparse
import hashlib
import itertools
import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]

DEFAULT_RULES = dict(f_min=6.0, f_max=16.0, alpha_exclude=[9.5, 10.5], harmonic_tolerance=0.15,
                     harmonics_checked=[2, 3], preferred_band=[6.5, 13.0], min_spacing=0.4, n_slots=6)


def candidates(refresh_hz: float, rules: dict) -> list[tuple[int, float]]:
    out = []
    for n in range(2, 200):
        f = refresh_hz / n
        if f < rules["f_min"] - 1e-9:
            break
        if f > rules["f_max"] + 1e-9:
            continue
        lo, hi = rules["alpha_exclude"]
        if lo <= f <= hi:
            continue
        out.append((n, f))
    return out


def set_is_valid(freqs: list[float], rules: dict) -> bool:
    tol = rules["harmonic_tolerance"]
    for a, b in itertools.permutations(freqs, 2):
        if abs(a - b) < rules["min_spacing"]:
            return False
        for h in rules["harmonics_checked"]:
            if abs(h * a - b) <= tol:
                return False
    return True


def score(freqs: list[float], rules: dict):
    lo, hi = rules["preferred_band"]
    in_band = sum(lo <= f <= hi for f in freqs)
    s = sorted(freqs)
    min_sp = min(b - a for a, b in zip(s, s[1:])) if len(s) > 1 else 99.0
    return (in_band, round(min_sp, 6), -sum(freqs) / len(freqs))


def compute(refresh_hz: float, rules: dict | None = None) -> dict:
    rules = {**DEFAULT_RULES, **(rules or {})}
    cands = candidates(refresh_hz, rules)
    best = None
    for k in range(min(rules["n_slots"], len(cands)), 1, -1):
        for combo in itertools.combinations(cands, k):
            fs = [f for _, f in combo]
            if not set_is_valid(fs, rules):
                continue
            sc = score(fs, rules)
            if best is None or sc > best[0]:
                best = (sc, combo)
        if best is not None:
            break
    if best is None:
        raise ValueError(f"no valid SSVEP frequency set for refresh {refresh_hz} Hz")
    combo = sorted(best[1], key=lambda nf: nf[1])
    slots = []
    for i, (n, f) in enumerate(combo):
        is_cancel = i == len(combo) - 1
        slots.append({"slot": "CANCEL" if is_cancel else i + 1, "frequency": round(f, 3),
                      "frequency_exact": f, "frames_per_cycle": n, "cancel": is_cancel})
    table = {"refresh_hz": refresh_hz, "slots": slots, "reduced": len(combo) < rules["n_slots"],
             "rules": rules}
    table["hash"] = table_hash(table)
    return table


def table_hash(table: dict) -> str:
    """Version hash shared by the headset and the decoder (mismatch -> red health gate)."""
    key = json.dumps({"refresh_hz": table["refresh_hz"],
                      "n": [s["frames_per_cycle"] for s in table["slots"]]}, sort_keys=True)
    return hashlib.sha256(key.encode()).hexdigest()[:12]


def load_rules() -> dict:
    cfg = yaml.safe_load((ROOT / "config/bci.yaml").read_text(encoding="utf-8"))
    return cfg.get("frequency_rules", {})


def configured_refresh() -> float:
    hw = yaml.safe_load((ROOT / "config/hardware.yaml").read_text(encoding="utf-8"))
    return float(hw["headset"]["refresh_hz"])


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--refresh", type=float, default=None)
    ap.add_argument("--out", default=str(ROOT / "config/generated/frequencies.yaml"))
    ap.add_argument("--print", action="store_true")
    a = ap.parse_args(argv)
    refresh = a.refresh or configured_refresh()
    t = compute(refresh, load_rules())
    out = Path(a.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("# GENERATED by tools/compute_frequencies.py. Do not edit.\n" + yaml.safe_dump(t, sort_keys=False))
    (out.with_suffix(".json")).write_text(json.dumps(t, indent=2))
    msg = ", ".join(f"{s['slot']}={s['frequency']}" for s in t["slots"])
    print(f"[frequencies] R={refresh} Hz -> {msg}  hash={t['hash']}" + ("  (REDUCED SET)" if t["reduced"] else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
